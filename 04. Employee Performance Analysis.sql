/* Business Question #33 - Employee Sales Ranking

-- Business Context
Management wants to rank employees
based on their sales performance.

-- Business Question
What is the sales ranking of each employee?
*/

-- QUERY

SELECT
    e.EmployeeID,
    e.EmployeeName,
    SUM(o.Quantity * o.UnitPrice * (1 - o.DiscountPct)) AS TotalRevenue,
    RANK() OVER (
        ORDER BY
            SUM(o.Quantity * o.UnitPrice * (1 - o.DiscountPct)) DESC
    ) AS SalesRank
FROM Orders o
INNER JOIN Employees e
    ON o.EmployeeID = e.EmployeeID
GROUP BY
    e.EmployeeID,
    e.EmployeeName
ORDER BY
    SalesRank;


/* Business Question #34 - Average Revenue per Employee

-- Business Context
Management wants to measure
the average revenue generated by employees.

-- Business Question
What is the average revenue generated per employee?
*/

-- QUERY

SELECT
    AVG(EmployeeRevenue) AS AverageRevenue
FROM
(
    SELECT
        EmployeeID,
        SUM(Quantity * UnitPrice * (1 - DiscountPct)) AS EmployeeRevenue
    FROM Orders
    GROUP BY EmployeeID
) AS EmployeeSales;


/* Business Question #35 - Employees Without Sales

-- Business Context
Management wants to identify employees
who have not generated any sales.

-- Business Question
Which employees have no sales records?
*/

-- QUERY

SELECT
    e.EmployeeID,
    e.EmployeeName
FROM Employees e
LEFT JOIN Orders o
    ON e.EmployeeID = o.EmployeeID
WHERE
    o.OrderID IS NULL
ORDER BY
    e.EmployeeID;


