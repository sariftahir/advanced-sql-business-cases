/* Business Question #38 - Department Revenue Contribution

-- Business Context
Management wants to measure
revenue contribution across departments.

-- Business Question
How much revenue does each department contribute?
*/

-- QUERY

SELECT
    d.DepartmentName,
    SUM(o.Quantity * o.UnitPrice * (1 - o.DiscountPct)) AS TotalRevenue
FROM Orders o
INNER JOIN Employees e
    ON o.EmployeeID = e.EmployeeID
INNER JOIN Departments d
    ON e.DepartmentID = d.DepartmentID
GROUP BY
    d.DepartmentName
ORDER BY
    TotalRevenue DESC;


/* Business Question #39 - Best Employee in Each Department

-- Business Context
Management wants to identify
the highest-performing employee in each department.

-- Business Question
Who is the top revenue-generating employee in every department?
*/

-- QUERY

WITH EmployeeRevenue AS
(
    SELECT
        d.DepartmentName,
        e.EmployeeID,
        e.EmployeeName,
        SUM(o.Quantity * o.UnitPrice * (1 - o.DiscountPct)) AS TotalRevenue,
        ROW_NUMBER() OVER
        (
            PARTITION BY d.DepartmentName
            ORDER BY
                SUM(o.Quantity * o.UnitPrice * (1 - o.DiscountPct)) DESC
        ) AS RowNum
    FROM Orders o
    INNER JOIN Employees e
        ON o.EmployeeID = e.EmployeeID
    INNER JOIN Departments d
        ON e.DepartmentID = d.DepartmentID
    GROUP BY
        d.DepartmentName,
        e.EmployeeID,
        e.EmployeeName
)

SELECT
    DepartmentName,
    EmployeeID,
    EmployeeName,
    TotalRevenue
FROM EmployeeRevenue
WHERE RowNum = 1
ORDER BY
    DepartmentName;


/* Business Question #40 - Employee Monthly Performance Trend

-- Business Context
Management wants to monitor
employee sales performance over time.

-- Business Question
How does employee revenue change each month?
*/

-- QUERY

SELECT
    e.EmployeeID,
    e.EmployeeName,
    YEAR(o.OrderDate) AS SalesYear,
    MONTH(o.OrderDate) AS SalesMonth,
    SUM(o.Quantity * o.UnitPrice * (1 - o.DiscountPct)) AS MonthlyRevenue
FROM Orders o
INNER JOIN Employees e
    ON o.EmployeeID = e.EmployeeID
GROUP BY
    e.EmployeeID,
    e.EmployeeName,
    YEAR(o.OrderDate),
    MONTH(o.OrderDate)
ORDER BY
    e.EmployeeName,
    SalesYear,
    SalesMonth;
