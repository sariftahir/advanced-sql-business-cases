/* Business Question #31 - Top Sales Employees

-- Business Context
Management wants to identify
the highest-performing sales employees.

-- Business Question
Which employees generate the highest total revenue?
*/

-- QUERY

SELECT
    e.EmployeeID,
    e.EmployeeName,
    SUM(o.Quantity * o.UnitPrice * (1 - o.DiscountPct)) AS TotalRevenue
FROM Orders o
INNER JOIN Employees e
    ON o.EmployeeID = e.EmployeeID
GROUP BY
    e.EmployeeID,
    e.EmployeeName
ORDER BY
    TotalRevenue DESC;


