/* Business Question #69 - Product Mix per Order

-- Business Context
Management wants to analyze
product variety within customer orders.

-- Business Question
How many different products are included in each order?
*/

-- QUERY

SELECT
    OrderID,
    COUNT(DISTINCT ProductID) AS NumberOfProducts
FROM Orders
GROUP BY
    OrderID
ORDER BY
    NumberOfProducts DESC;


/* Business Question #70 - Peak Operational Days

-- Business Context
Management wants to identify
the busiest operational days.

-- Business Question
Which days have the highest order volume?
*/

-- QUERY

SELECT
    DATENAME(WEEKDAY, OrderDate) AS DayName,
    COUNT(DISTINCT OrderID) AS TotalOrders
FROM Orders
GROUP BY
    DATENAME(WEEKDAY, OrderDate)
ORDER BY
    TotalOrders DESC;
