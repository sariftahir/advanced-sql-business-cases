/* Business Question #89 - Top Performing Business Areas

-- Business Context
Management wants to identify
the highest-performing business departments.

-- Business Question
Which departments generate the highest revenue?
*/

-- QUERY

SELECT
    d.DepartmentName,
    SUM(o.Quantity * o.UnitPrice * (1 - o.DiscountPct)) AS TotalRevenue
FROM Orders o
INNER JOIN Employees e
    ON o.EmployeeID = e.EmployeeID
INNER JOIN Departments d
    ON e.DepartmentID = d.DepartmentID
GROUP BY
    d.DepartmentName
ORDER BY
    TotalRevenue DESC;
/* Business Question #90 - Executive Sales Dashboard Dataset

-- Business Context
Executives require a consolidated dataset
to support strategic decision-making.

-- Business Question
What dataset can be prepared
for an executive sales dashboard?
*/

-- QUERY

SELECT
    o.OrderID,
    o.OrderDate,
    c.CustomerID,
    c.CustomerName,
    c.CustomerSegment,
    c.City,
    p.ProductID,
    p.ProductName,
    ca.CategoryName,
    e.EmployeeName,
    d.DepartmentName,
    o.Quantity,
    o.UnitPrice,
    o.UnitCost,
    o.DiscountPct,
    (o.Quantity * o.UnitPrice * (1 - o.DiscountPct)) AS Revenue,
    ((o.UnitPrice - o.UnitCost) * o.Quantity * (1 - o.DiscountPct)) AS Profit
FROM Orders o
INNER JOIN Customers c
    ON o.CustomerID = c.CustomerID
INNER JOIN Products p
    ON o.ProductID = p.ProductID
INNER JOIN Categories ca
    ON p.CategoryID = ca.CategoryID
INNER JOIN Employees e
    ON o.EmployeeID = e.EmployeeID
INNER JOIN Departments d
    ON e.DepartmentID = d.DepartmentID;
