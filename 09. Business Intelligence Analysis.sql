/* Business Question #84 - Revenue Share by Product Category

-- Business Context
Management wants to understand
the revenue contribution of each category.

-- Business Question
How much revenue does each product category contribute?
*/

-- QUERY

SELECT
    ca.CategoryName,
    SUM(o.Quantity * o.UnitPrice * (1 - o.DiscountPct)) AS TotalRevenue
FROM Orders o
INNER JOIN Products p
    ON o.ProductID = p.ProductID
INNER JOIN Categories ca
    ON p.CategoryID = ca.CategoryID
GROUP BY
    ca.CategoryName
ORDER BY
    TotalRevenue DESC;
/* Business Question #85 - Executive KPI Summary

-- Business Context
Executives need a single report
containing key business metrics.

-- Business Question
What are the company's key sales KPIs?
*/

-- QUERY

SELECT
    COUNT(DISTINCT OrderID) AS TotalOrders,
    COUNT(DISTINCT CustomerID) AS TotalCustomers,
    COUNT(DISTINCT ProductID) AS TotalProducts,
    SUM(Quantity) AS TotalQuantitySold,
    SUM(Quantity * UnitPrice * (1 - DiscountPct)) AS TotalRevenue,
    SUM((UnitPrice - UnitCost) * Quantity * (1 - DiscountPct)) AS TotalProfit
FROM Orders;
