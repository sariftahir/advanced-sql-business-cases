/* Business Question #81 - Pareto Analysis (80/20)

-- Business Context
Management wants to identify
whether a small percentage of customers
contribute the majority of revenue.

-- Business Question
Which customers contribute approximately 80% of total revenue?
*/

-- QUERY

WITH CustomerRevenue AS
(
    SELECT
        c.CustomerID,
        c.CustomerName,
        SUM(o.Quantity * o.UnitPrice * (1 - o.DiscountPct)) AS TotalRevenue
    FROM Orders o
    INNER JOIN Customers c
        ON o.CustomerID = c.CustomerID
    GROUP BY
        c.CustomerID,
        c.CustomerName
),
RevenueRank AS
(
    SELECT
        *,
        SUM(TotalRevenue) OVER
        (
            ORDER BY TotalRevenue DESC
        ) AS RunningRevenue,
        SUM(TotalRevenue) OVER () AS OverallRevenue
    FROM CustomerRevenue
)

SELECT
    CustomerID,
    CustomerName,
    TotalRevenue,
    RunningRevenue,
    OverallRevenue,
    ROUND(RunningRevenue * 100.0 / OverallRevenue,2) AS CumulativePct
FROM RevenueRank
ORDER BY
    TotalRevenue DESC;
