/* Business Question #11 - Top Customers by Revenue

-- Business Context
The Marketing Team wants to identify the highest-value customers
based on the total revenue they generated.

-- Business Question
Which customers generated the highest total revenue?
*/

-- QUERY

SELECT
    c.CustomerID,
    c.CustomerName,
    SUM(o.Quantity * o.UnitPrice * (1 - o.DiscountPct)) AS TotalRevenue
FROM Orders o
INNER JOIN Customers c
    ON o.CustomerID = c.CustomerID
GROUP BY
    c.CustomerID,
    c.CustomerName
ORDER BY
    TotalRevenue DESC;


/* Business Question #12 - Customer Performance by Location

-- Business Context
Management wants to compare customer revenue
across different locations.

-- Business Question
Which customer locations generate the highest revenue?
*/

-- QUERY

SELECT
    c.City,
    COUNT(DISTINCT c.CustomerID) AS TotalCustomers,
    SUM(o.Quantity * o.UnitPrice * (1 - o.DiscountPct)) AS TotalRevenue
FROM Orders o
INNER JOIN Customers c
    ON o.CustomerID = c.CustomerID
GROUP BY
    c.City
ORDER BY
    TotalRevenue DESC;


/* Business Question #13 - Repeat Purchase Customers

-- Business Context
The Marketing Team wants to identify loyal customers
who have made multiple purchases.

-- Business Question
Which customers have placed more than one order?
*/

-- QUERY

SELECT
    c.CustomerID,
    c.CustomerName,
    COUNT(DISTINCT o.OrderID) AS TotalOrders
FROM Orders o
INNER JOIN Customers c
    ON o.CustomerID = c.CustomerID
GROUP BY
    c.CustomerID,
    c.CustomerName
HAVING COUNT(DISTINCT o.OrderID) > 1
ORDER BY
    TotalOrders DESC;


