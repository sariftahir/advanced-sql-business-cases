/* Business Question #18 - Customer Purchase Frequency

-- Business Context
Management wants to understand how frequently
customers make purchases.

-- Business Question
How many days, on average, are there between purchases for each customer?
*/

-- QUERY

WITH PurchaseHistory AS (
    SELECT
        CustomerID,
        OrderDate,
        LAG(OrderDate) OVER (
            PARTITION BY CustomerID
            ORDER BY OrderDate
        ) AS PreviousOrderDate
    FROM Orders
)

SELECT
    CustomerID,
    AVG(DATEDIFF(DAY, PreviousOrderDate, OrderDate) * 1.0) AS AvgDaysBetweenPurchases
FROM PurchaseHistory
WHERE PreviousOrderDate IS NOT NULL
GROUP BY CustomerID
ORDER BY AvgDaysBetweenPurchases;


/* Business Question #19 - Inactive Customers

-- Business Context
The Marketing Team wants to identify customers
who have not made purchases recently.

-- Business Question
Which customers have not placed an order in the last 90 days?
*/

-- QUERY

SELECT
    c.CustomerID,
    c.CustomerName,
    MAX(o.OrderDate) AS LastPurchaseDate
FROM Orders o
INNER JOIN Customers c
    ON o.CustomerID = c.CustomerID
GROUP BY
    c.CustomerID,
    c.CustomerName
HAVING MAX(o.OrderDate) < DATEADD(DAY, -90, GETDATE())
ORDER BY
    LastPurchaseDate;


/* Business Question #20 - Customer Revenue Ranking

-- Business Context
Management wants to rank customers
based on their total revenue contribution.

-- Business Question
How does each customer rank by total revenue generated?
*/

-- QUERY

SELECT
    c.CustomerID,
    c.CustomerName,
    SUM(o.Quantity * o.UnitPrice * (1 - o.DiscountPct)) AS TotalRevenue,
    RANK() OVER (
        ORDER BY SUM(o.Quantity * o.UnitPrice * (1 - o.DiscountPct)) DESC
    ) AS RevenueRank
FROM Orders o
INNER JOIN Customers c
    ON o.CustomerID = c.CustomerID
GROUP BY
    c.CustomerID,
    c.CustomerName
ORDER BY
    RevenueRank;
