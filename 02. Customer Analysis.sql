/* Business Question #15 - New vs Returning Customers

-- Business Context
Management wants to understand the balance between
new and returning customers.

-- Business Question
How many customers are new and how many are returning?
*/

-- QUERY

WITH CustomerOrders AS (
    SELECT
        CustomerID,
        COUNT(DISTINCT OrderID) AS TotalOrders
    FROM Orders
    GROUP BY CustomerID
)

SELECT
    CASE
        WHEN TotalOrders = 1 THEN 'New Customer'
        ELSE 'Returning Customer'
    END AS CustomerType,
    COUNT(*) AS TotalCustomers
FROM CustomerOrders
GROUP BY
    CASE
        WHEN TotalOrders = 1 THEN 'New Customer'
        ELSE 'Returning Customer'
    END;


